const { contextBridge, ipcRenderer } = require("electron");
const constants = require("./shared/constants.cjs");
const { DICTS, LANGUAGES } = require("./shared/i18n.cjs");
const invoke = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld("tv", {
  constants,
  i18n: { dicts: DICTS, languages: LANGUAGES },
  getConfig: invoke("config:get"),
  saveConfig: invoke("config:save"),
  getState: invoke("tv:get"),
  pair: invoke("tv:pair"),
  sendCode: invoke("tv:code"),
  reconnect: invoke("tv:reconnect"),
  forget: invoke("tv:forget"),
  key: invoke("tv:key"),
  power: invoke("tv:power"),
  app: invoke("tv:app"),
  text: invoke("tv:text"),
  setVolume: invoke("tv:volume"),
  setInput: invoke("ui:input"),
  hide: invoke("win:hide"),
  quit: invoke("win:quit"),
  openExternal: invoke("open:external"),
  launch: invoke("tv:launch"),
  acGet: invoke("ac:get"), acConnect: invoke("ac:connect"), acLearn: invoke("ac:learn"), acCancelLearn: invoke("ac:cancelLearn"),
  acForget: invoke("ac:forget"), acSet: invoke("ac:set"), acConfig: invoke("ac:config"),
  onAc: (cb) => ipcRenderer.on("ac:state", (_e, s) => cb(s)),
  adbGet: invoke("adb:get"),
  adbConnect: invoke("adb:connect"),
  adbDisconnect: invoke("adb:disconnect"),
  onAdb: (cb) => ipcRenderer.on("adb:state", (_e, s) => cb(s)),
  castGet: invoke("cast:get"),
  castPlay: invoke("cast:play"),
  castControl: invoke("cast:control"),
  castStopApp: invoke("cast:stopApp"),
  castMute: invoke("cast:mute"),
  castFile: invoke("cast:file"),
  onCast: (cb) => ipcRenderer.on("cast:state", (_e, s) => cb(s)),
  onState: (cb) => ipcRenderer.on("tv:state", (_e, s) => cb(s)),
  onConfig: (cb) => ipcRenderer.on("config", (_e, c) => cb(c)),
  onArrow: (cb) => ipcRenderer.on("win:arrow", (_e, x) => cb(x)),
});
