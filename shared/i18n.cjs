const DICTS = { es };
function makeT(locale) {
  const lang = String(locale || "en").toLowerCase().split(/[-_]/)[0];
  const dict = DICTS[lang] || {};
  const t = (key, vars) => {
    let s = dict[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    return s;
  };
  t.lang = DICTS[lang] ? lang : "en";
  return t;
}
